const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const ROOT = '/mnt/c/parchee';
process.chdir(ROOT);

function log(step, msg) {
  console.log('\n\x1b[36m[' + step + ']\x1b[0m ' + msg);
}

function run(cmd, allowFail) {
  console.log('  $ ' + cmd);
  try {
    return execSync(cmd, {
      cwd: ROOT,
      stdio: 'inherit',
      env: Object.assign({}, process.env, { FORCE_COLOR: '1' }),
    });
  } catch (err) {
    if (!allowFail) throw err;
    return null;
  }
}

function runCapture(cmd) {
  try {
    return execSync(cmd, { cwd: ROOT, encoding: 'utf8' }).trim();
  } catch (_e) {
    return '';
  }
}

function writeLines(relPath, lines) {
  const fullPath = path.join(ROOT, relPath);
  fs.mkdirSync(path.dirname(fullPath), { recursive: true });
  fs.writeFileSync(fullPath, lines.join('\n') + '\n', 'utf8');
  console.log('  ✔ Wrote ' + relPath);
}

